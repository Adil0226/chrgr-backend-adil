// Builds data/seed.sql (schema + INSERTs) from data/chargers.json
const fs = require('fs');
const path = require('path');
const { SCHEMA } = require('./db');
const { loadSeedData } = require('./seed');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = loadSeedData().map(
  (c) => `(${q(c.name)}, ${q(c.location_name)}, ${c.latitude}, ${c.longitude}, ${q(c.connector_type)}, ${q(c.operator)}, ${q(c.city)})`
);
const sql =
  `-- Generated by "npm run sql" from data/chargers.json\n${SCHEMA}\n` +
  `INSERT INTO chargers (name, location_name, latitude, longitude, connector_type, operator, city) VALUES\n` +
  rows.join(',\n') + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'data', 'seed.sql'), sql);
console.log(`Wrote data/seed.sql with ${rows.length} chargers`);
